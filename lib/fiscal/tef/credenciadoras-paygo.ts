export function cnpjCredenciadoraPayGo(rede: string | null | undefined) {
  const chave = String(rede ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
  if (!chave) {
    return null;
  }
  return CREDENCIADORAS_PAYGO[chave] ?? null;
}
